"""Count the Vietnamese rhymes the dev split uses and write them as a table.

Dev only, never test. rank.py penalises a candidate whose rhyme never appears
here, which is the "penalty for rare rhymes" of docs/brief.md step 6 without pulling
in a Vietnamese corpus.

    uv run scripts/build_rhymes.py
"""
import collections
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from boi import vi  # noqa: E402

DEV = ROOT / "data" / "splits" / "dev.csv"
OUT = ROOT / "src" / "boi" / "rhymes.py"

HEADER = '''"""Vietnamese rhymes (nucleus, coda) counted in the dev split.

Generated by scripts/build_rhymes.py. Do not edit by hand.
Dev rows only, so nothing here leaks from the test split.
"""

RHYMES = {
'''


def main():
    counts = collections.Counter()
    with open(DEV, encoding="utf-8") as f:
        for row in csv.DictReader(f):
            forms = [row["vi_form"]] + [a for a in row["alt_forms"].split(";") if a]
            for form in forms:
                for syl in vi.parse_word(form):
                    counts[(syl.nucleus, syl.coda)] += 1

    lines = [HEADER]
    for (nucleus, coda), n in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0])):
        lines.append(f'    ({nucleus!r}, {coda!r}): {n},\n')
    lines.append("}\n")
    OUT.write_text("".join(lines), encoding="utf-8")
    print(f"{len(counts)} rhymes -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
